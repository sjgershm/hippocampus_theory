"""
Theta-skipping pacemaker: the branch selector that makes sweeps alternate.

Rollouts are generated by inverse-transform sampling from a stream of uniforms
(`model.sample_trajectory(..., u=...)`), and at a choice point the destination is
picked from the inverse-CDF strata, so a single uniform decides the branch. The
pacemaker supplies *that* uniform, drawn not independently each cycle but from a
slowly diffusing phase locked to half the theta frequency:

    u^k = (u^0 + k/2 + eps^k) mod 1,     eps^k = eps^{k-1} + eta^k
    u^0 ~ Uniform[0, 1),                 eta^k ~ N(0, sigma_eta^2)

Branch j is chosen on cycle k iff u^k falls in its stratum I_j (|I_j| = p_j).

Two properties, both derived in DERIVATIONS §C.11:

  * MARGINAL CONSISTENCY. u^k ~ Uniform[0,1) for every k, because a uniform on
    the circle stays uniform under convolution with any independent variable.
    So P(branch j on cycle k) = p_j exactly -- the sampler stays faithful to the
    master equation for any sigma_eta, at any choice point, with nothing to
    calibrate.
  * ALTERNATION. The +1/2 drift flips the branch every cycle; the diffusion lets
    it occasionally fail. The adjacent-switch rate has the closed form
        q(sigma) = 1/2 + (4/pi^2) sum_{n odd} n^-2 exp(-2 pi^2 n^2 sigma^2)
    (approximately 1 - 1.596 sigma for small sigma), and sigma_eta = 0.075 gives
    q = 0.880 with 0.796 of triplets alternating -- the 79.8% reported by
    Vollan et al. (2025).

The diffusion has to ACCUMULATE. I.i.d. jitter about a fixed phase satisfies the
same marginal but never forgets u^0, leaving a variance floor that does not shrink
with the number of cycles (DERIVATIONS §C.11.5).
"""

from __future__ import annotations

import numpy as np

SIGMA_ETA = 0.075        # reproduces the observed alternation rate


def pacemaker_phases(n_cycles: int, rng: np.random.Generator,
                     sigma: float = SIGMA_ETA) -> np.ndarray:
    """The sequence u^1..u^n of pacemaker values (one per theta cycle)."""
    eta = rng.normal(0.0, sigma, n_cycles)
    eta[0] = 0.0                                   # eps^0 = 0
    eps = np.cumsum(eta)
    return (rng.random() + np.arange(n_cycles) / 2.0 + eps) % 1.0


def branch_stream(rng: np.random.Generator, u_branch: float,
                  branch_index: int = 1):
    """A uniform stream for one rollout: fresh uniforms everywhere except at
    `branch_index`, which returns the pacemaker value.

    `sample_trajectory` consumes two uniforms per jump -- dwell time, then
    destination -- so for a sweep launched *at* the choice point the branch is
    decided by the second draw, index 1. Everything else about the rollout
    (dwell times, the run down the arm) is drawn independently, exactly as in
    the uncoupled sampler.
    """
    pos = [0]

    def draw() -> float:
        i = pos[0]
        pos[0] += 1
        return float(u_branch) if i == branch_index else float(rng.random())

    return draw
